"""Generate native simavr registration headers from CMake's exact core list.

Preserve the vendor filename CONFIG convention and version ``unknown``. CMake
compiles every supplied core, so compilation errors remain fatal. In particular
this retains the existing MEGA169/MEGA169P registration mismatch; it does not
silently add a device. Output order is deterministic and no Git/source writes
or external toolchain discovery are required.
"""
import argparse
from pathlib import Path
import re


def generate(core_paths, output_dir):
    cores = sorted((Path(p) for p in core_paths), key=lambda p: p.name)
    if not cores or len({p.name for p in cores}) != len(cores):
        raise ValueError("core sources must be nonempty with unique filenames")
    macros, kinds = [], []
    for core in cores:
        if not re.fullmatch(r"sim_[a-zA-Z0-9_]+\.c", core.name):
            raise ValueError("unexpected core filename: " + core.name)
        macros.append(core.stem[4:].upper())
        kinds.extend(re.findall(r"^avr_kind_t\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{",
                                core.read_text(encoding="utf-8"), re.M))
    if len(kinds) != len(set(kinds)):
        raise ValueError("duplicate core registration")
    config = "// Autogenerated do not edit\n#ifndef __SIM_CORE_CONFIG_H__\n#define __SIM_CORE_CONFIG_H__\n\n"
    config += '#define CONFIG_SIMAVR_VERSION "unknown"\n'
    config += "".join("#define CONFIG_" + macro + " 1\n" for macro in macros) + "\n#endif\n"
    decl = "// Autogenerated do not edit\n#ifndef __SIM_CORE_DECL_H__\n#define __SIM_CORE_DECL_H__\n\n"
    decl += '#include "sim_core_config.h"\n'
    decl += "".join("#if CONFIG_" + kind.upper() + "\nextern avr_kind_t " + kind + ";\n#endif\n"
                    for kind in kinds)
    decl += "\nextern avr_kind_t * avr_kind[];\n#ifdef AVR_KIND_DECL\navr_kind_t * avr_kind[] = {\n"
    decl += "".join("#if CONFIG_" + kind.upper() + "\n\t&" + kind + ",\n#endif\n" for kind in kinds)
    decl += "\tNULL\n};\n#endif\n#endif\n"
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    for name, text in (("sim_core_config.h", config), ("sim_core_decl.h", decl)):
        with (output / name).open("w", encoding="utf-8", newline="\n") as sink:
            sink.write(text)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("cores", nargs="+")
    arguments = parser.parse_args()
    generate(arguments.cores, arguments.output_dir)
